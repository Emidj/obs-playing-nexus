"""Generate native and installer catalogs from the reviewed five-language source."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
LANGUAGES=['es','en','it','fr','de']
def catalog():
    rows={}
    for line in (ROOT/'locales/messages.tsv').read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'):continue
        values=[v.replace('\\r','\r').replace('\\n','\n') for v in line.split('|')]
        assert len(values)==5 and all(values),line
        source=values[0];assert source not in rows,f'Duplicate: {source}'
        for value in values:
            assert sorted(re.findall(r'%[1-9]',source))==sorted(re.findall(r'%[1-9]',value)),source
        rows[source]=values
    # The source retained some English dashboard terms; Spanish is translated too.
    spanish={'CURRENT TRACK':'CANCIÓN ACTUAL','NETWORK':'RED','CONNECTED CLIENTS':'CLIENTES CONECTADOS','AUTO DETECTOR':'DETECTOR AUTOMÁTICO',
             'Serato DJ Pro (Automatic)':'Serato DJ Pro (Automático)','Automatic':'Automático','History':'Historial','Fade':'Fundido','Slide':'Deslizamiento','Layout':'Distribución',
             'All (*.*)':'Todos los archivos (*.*)','Profile (*.pcs)':'Perfil (*.pcs)',
             'Images (*.png *.jpg *.jpeg *.webp *.svg)':'Imágenes (*.png *.jpg *.jpeg *.webp *.svg)',
             '●  Connected':'●  Conectado','●  Disconnected':'●  Desconectado','●  Running':'●  En ejecución','●  Stopped':'●  Detenido','  ·  Connected':'  ·  Conectado'}
    for source,value in spanish.items():rows[source][0]=value
    return rows
